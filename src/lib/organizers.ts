// Server-only: organizer accounts (the platform's paying customers) and their
// portal sessions. Accounts are created by the platform admin; organizers log
// in with email + password and only ever see their own events and orders.
import crypto from 'crypto';
import { cookies } from 'next/headers';
import { getDb } from './db';
import { getSigningSecret } from './auth';
import { burnOrganizerLoginCodes } from './loginCode';
import { burnOrganizerResetCodes } from './passwordReset';

export const ORGANIZER_COOKIE_NAME = 'organizer_session';
export const ORGANIZER_SESSION_TTL_MS = 7 * 24 * 60 * 60 * 1000; // a week

export type OrganizerStatus = 'active' | 'disabled' | 'pending';

export interface OrganizerRow {
  id: string;
  email: string;
  name: string;
  status: OrganizerStatus;
  planPaidUntil: string | null; // 'YYYY-MM-DD'
  notes: string;
  createdAt: string;
  hasPassword: boolean;
  /**
   * The current password was generated by the platform and emailed, so it is a
   * one-time password: the portal stays locked behind /portal/change-password
   * until the organizer replaces it with one only they know.
   */
  mustChangePassword: boolean;
}

const ORG_COLS = `
  id, email, name, status,
  plan_paid_until AS planPaidUntil,
  notes,
  created_at AS createdAt,
  (password_hash != '') AS hasPassword,
  must_change_password AS mustChangePassword
`;

function toRow(r: Record<string, unknown> | undefined): OrganizerRow | null {
  if (!r) return null;
  return {
    ...(r as unknown as OrganizerRow),
    hasPassword: Boolean(r.hasPassword),
    mustChangePassword: Boolean(r.mustChangePassword),
  };
}

// ---------------- Password hashing (scrypt, no extra deps) ----------------

export function hashPassword(password: string): string {
  const salt = crypto.randomBytes(16).toString('hex');
  const hash = crypto.scryptSync(password, salt, 64).toString('hex');
  return `${salt}:${hash}`;
}

export function verifyPassword(password: string, stored: string): boolean {
  const [salt, hash] = (stored || '').split(':');
  if (!salt || !hash) return false;
  const candidate = crypto.scryptSync(password, salt, 64);
  const expected = Buffer.from(hash, 'hex');
  return candidate.length === expected.length && crypto.timingSafeEqual(candidate, expected);
}

// ---------------- CRUD (platform-admin operations) ----------------

export function listOrganizers(): OrganizerRow[] {
  const rows = getDb().prepare(`SELECT ${ORG_COLS} FROM organizers ORDER BY created_at DESC`).all() as Record<
    string,
    unknown
  >[];
  return rows.map((r) => toRow(r)!);
}

export function getOrganizer(id: string): OrganizerRow | null {
  return toRow(getDb().prepare(`SELECT ${ORG_COLS} FROM organizers WHERE id = ?`).get(id) as Record<string, unknown>);
}

export function getOrganizerByEmail(email: string): OrganizerRow | null {
  return toRow(
    getDb().prepare(`SELECT ${ORG_COLS} FROM organizers WHERE email = ?`).get(email.trim()) as Record<string, unknown>
  );
}

/** A fresh one-time password. Only ever returned to the platform admin, once. */
function generateInitialPassword(): string {
  return crypto.randomBytes(9).toString('base64').replace(/[+/=]/g, '').slice(0, 12);
}

/**
 * Create an organizer account. Returns the generated initial password.
 * Accounts do not expire (the platform fee is per event), so planPaidUntil
 * defaults to the never-expires sentinel. The password is one-time: the
 * organizer is made to replace it before the portal opens.
 */
export function createOrganizer(params: {
  email: string;
  name: string;
  planPaidUntil?: string | null;
  notes?: string;
}): { organizer: OrganizerRow; initialPassword: string } {
  const initialPassword = generateInitialPassword();
  const id = crypto.randomUUID();
  getDb()
    .prepare(
      `INSERT INTO organizers (id, email, name, password_hash, status, plan_paid_until, notes, must_change_password)
       VALUES (?, ?, ?, ?, 'active', ?, ?, 1)`
    )
    .run(
      id,
      params.email.trim(),
      params.name.trim(),
      hashPassword(initialPassword),
      params.planPaidUntil ?? PLAN_NEVER_EXPIRES,
      params.notes ?? ''
    );
  return { organizer: getOrganizer(id)!, initialPassword };
}

export function setOrganizerStatus(id: string, status: OrganizerStatus): void {
  getDb().prepare(`UPDATE organizers SET status = ? WHERE id = ?`).run(status, id);
  // Locking an account also kills any "forgot my password" code it was handed:
  // a disabled organizer must not be able to let themselves back in with a code
  // minted minutes earlier. (The reset route re-checks status at the final step
  // too — this just means the code is gone rather than merely useless.)
  if (status !== 'active') {
    burnOrganizerResetCodes(id);
    burnOrganizerLoginCodes(id);
  }
}

export function setOrganizerPlanPaidUntil(id: string, date: string | null): void {
  getDb().prepare(`UPDATE organizers SET plan_paid_until = ? WHERE id = ?`).run(date, id);
}

/**
 * Reset to a fresh random password (platform admin hands it to the organizer).
 * Like a brand-new account, the organizer must replace it on the way in.
 */
export function resetOrganizerPassword(id: string): string {
  const pw = generateInitialPassword();
  getDb()
    .prepare(`UPDATE organizers SET password_hash = ?, must_change_password = 1 WHERE id = ?`)
    .run(hashPassword(pw), id);
  burnOrganizerResetCodes(id);
  burnOrganizerLoginCodes(id);
  return pw;
}

/**
 * The organizer picked this one themselves, so the forced change is over.
 *
 * Every outstanding reset code goes with it — the one just used and any other
 * still in an inbox. Whoever knows the new password is in; an old code must not
 * be a second way back.
 */
export function setOrganizerPassword(id: string, password: string): void {
  getDb()
    .prepare(`UPDATE organizers SET password_hash = ?, must_change_password = 0 WHERE id = ?`)
    .run(hashPassword(password), id);
  burnOrganizerResetCodes(id);
  burnOrganizerLoginCodes(id);
}

/**
 * Sentinel paid-until date for accounts that never run out. Accounts are free
 * under per-event pricing — the money is charged per published event — but the
 * column stays filled so older data, badges, and exports keep making sense.
 */
export const PLAN_NEVER_EXPIRES = '9999-12-31';

/** Activate a signup: the account is free, so it never expires again. */
export function activateOrganizer(id: string): void {
  getDb()
    .prepare(`UPDATE organizers SET status = 'active', plan_paid_until = ? WHERE id = ?`)
    .run(PLAN_NEVER_EXPIRES, id);
}

/**
 * Verify credentials WITHOUT requiring active status — callers branch on
 * status so pending signups can see their payment instructions after login.
 */
export function checkOrganizerCredentials(email: string, password: string): OrganizerRow | null {
  const row = getDb()
    .prepare(`SELECT ${ORG_COLS}, password_hash AS passwordHash FROM organizers WHERE email = ?`)
    .get(email.trim()) as (Record<string, unknown> & { passwordHash: string }) | undefined;
  if (!row || !row.passwordHash) return null;
  if (!verifyPassword(password, row.passwordHash)) return null;
  return toRow(row);
}

export function checkOrganizerLogin(email: string, password: string): OrganizerRow | null {
  const row = getDb()
    .prepare(`SELECT ${ORG_COLS}, password_hash AS passwordHash FROM organizers WHERE email = ?`)
    .get(email.trim()) as (Record<string, unknown> & { passwordHash: string }) | undefined;
  if (!row || !row.passwordHash) return null;
  if (!verifyPassword(password, row.passwordHash)) return null;
  const organizer = toRow(row)!;
  return organizer.status === 'active' ? organizer : null;
}

/**
 * Portal access. Under per-event pricing the ACCOUNT is free and never
 * expires — organizers pay per event when they publish one — so this is true
 * for every active account. Only a disabled (or still pending) account is
 * locked out; the guards and <PlanExpired/> stay in place for that case.
 */
export function organizerPlanActive(o: OrganizerRow): boolean {
  return o.status === 'active';
}

// ---------------- Sessions (HMAC cookie: 'org.<id>.<exp>.<mac>') ----------------
//
// The MAC covers a fingerprint of the CURRENT password hash, so changing or
// resetting the password instantly revokes every outstanding session token
// (the stored hash changes -> old MACs no longer verify).

/** Raw password_hash for an organizer, or null when the organizer is missing. */
function organizerPasswordHash(id: string): string | null {
  const row = getDb().prepare(`SELECT password_hash AS hash FROM organizers WHERE id = ?`).get(id) as
    | { hash: string }
    | undefined;
  return row ? row.hash : null;
}

/** Short fingerprint of the password hash bound into session MACs. */
function passwordHashFingerprint(passwordHash: string): string {
  return crypto.createHash('sha256').update(passwordHash).digest('hex').slice(0, 12);
}

function signOrganizer(id: string, exp: number, hash12: string, secret: string): string {
  return crypto.createHmac('sha256', secret).update(`organizer:${id}:${exp}:${hash12}`).digest('hex');
}

export function createOrganizerSessionToken(organizerId: string): string {
  const secret = getSigningSecret();
  if (!secret) throw new Error('Auth is not configured (set APP_SECRET)');
  const passwordHash = organizerPasswordHash(organizerId);
  if (passwordHash === null) throw new Error('Unknown organizer');
  const exp = Date.now() + ORGANIZER_SESSION_TTL_MS;
  const hash12 = passwordHashFingerprint(passwordHash);
  return `org.${organizerId}.${exp}.${signOrganizer(organizerId, exp, hash12, secret)}`;
}

/**
 * A short-lived ticket proving "this password was correct" — the half-finished
 * state between a right password and a right authenticator code.
 *
 * It is NOT a session: it grants nothing on its own, and only the second-factor
 * route accepts it. Five minutes is long enough to open an authenticator app
 * and short enough that one left in a browser history is worthless.
 *
 * Bound to the password hash exactly like a session, so changing or resetting
 * the password invalidates any pending login already in flight.
 */
const PENDING_TTL_MS = 5 * 60_000;

function signPending(id: string, exp: number, hash12: string, secret: string): string {
  return crypto.createHmac('sha256', secret).update(`organizer-2fa:${id}:${exp}:${hash12}`).digest('hex');
}

export function createOrganizerPendingToken(organizerId: string): string {
  const secret = getSigningSecret();
  if (!secret) throw new Error('Auth is not configured (set APP_SECRET)');
  const passwordHash = organizerPasswordHash(organizerId);
  if (passwordHash === null) throw new Error('Unknown organizer');
  const exp = Date.now() + PENDING_TTL_MS;
  return `pend.${organizerId}.${exp}.${signPending(organizerId, exp, passwordHashFingerprint(passwordHash), secret)}`;
}

export function verifyOrganizerPendingToken(token: string | null | undefined): string | null {
  if (!token) return null;
  const secret = getSigningSecret();
  if (!secret) return null;
  const parts = token.split('.');
  if (parts.length !== 4 || parts[0] !== 'pend') return null;
  const [, id, expStr, mac] = parts;
  if (!id || !/^\d+$/.test(expStr)) return null;
  const exp = Number(expStr);
  if (!Number.isFinite(exp) || exp <= Date.now()) return null;
  const passwordHash = organizerPasswordHash(id);
  if (passwordHash === null) return null;
  const expected = signPending(id, exp, passwordHashFingerprint(passwordHash), secret);
  const ha = crypto.createHash('sha256').update(mac).digest();
  const hb = crypto.createHash('sha256').update(expected).digest();
  if (!crypto.timingSafeEqual(ha, hb)) return null;
  return id;
}

export function verifyOrganizerSessionToken(token: string | null | undefined): string | null {
  if (!token) return null;
  const secret = getSigningSecret();
  if (!secret) return null;
  const parts = token.split('.');
  if (parts.length !== 4 || parts[0] !== 'org') return null;
  const [, id, expStr, mac] = parts;
  if (!id || !/^\d+$/.test(expStr)) return null;
  const exp = Number(expStr);
  if (!Number.isFinite(exp) || exp <= Date.now()) return null;
  const passwordHash = organizerPasswordHash(id);
  if (passwordHash === null) return null; // organizer no longer exists
  const expected = signOrganizer(id, exp, passwordHashFingerprint(passwordHash), secret);
  const ha = crypto.createHash('sha256').update(mac).digest();
  const hb = crypto.createHash('sha256').update(expected).digest();
  if (!crypto.timingSafeEqual(ha, hb)) return null;
  return id;
}

/**
 * The signed-in organizer for this request, or null. Checks the account is
 * still active (a disabled organizer's existing cookie stops working).
 */
export async function currentOrganizer(): Promise<OrganizerRow | null> {
  const store = await cookies();
  const id = verifyOrganizerSessionToken(store.get(ORGANIZER_COOKIE_NAME)?.value ?? null);
  if (!id) return null;
  const organizer = getOrganizer(id);
  return organizer && organizer.status === 'active' ? organizer : null;
}
