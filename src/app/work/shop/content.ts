const NE_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
/** Digits in Devanagari for नेपाली. */
export function num(s: string | number, lang: Lang): string {
  const v = String(s);
  return lang === 'ne' ? v.replace(/[0-9]/g, (d) => NE_DIGITS[Number(d)]) : v;
}
/** 1234 → "1,234" / "1.234" / "१,२३४"; 2.5 → "2.5" / "2,5". */
export function count(n: number, lang: Lang): string {
  const neg = n < 0;
  const [int, frac] = String(Math.abs(Math.round(n * 10) / 10)).split('.');
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, lang === 'de' ? '.' : ',');
  const s = (neg ? '−' : '') + grouped + (frac ? (lang === 'de' ? ',' : '.') + frac : '');
  return num(s, lang);
}
export const LOCALE: Record<Lang, string> = { en: 'en-GB', de: 'de-DE', ne: 'ne-NP' };

/** A calendar day (days since 1970) as text: "Tue 3 Nov", "Di., 3. Nov.", "मंगल, ३ नोभेम्बर". */
export function dayLabel(day: number, lang: Lang, opts: Intl.DateTimeFormatOptions = { weekday: 'short', day: 'numeric', month: 'short' }): string {
  try {
    return new Intl.DateTimeFormat(LOCALE[lang], { ...opts, timeZone: 'UTC' }).format(new Date(day * 86400000));
  } catch {
    return new Date(day * 86400000).toISOString().slice(0, 10);
  }
}
export function hhmm(min: number, lang: Lang): string {
  return num(`${String(Math.floor(min / 60)).padStart(2, '0')}:${String(min % 60).padStart(2, '0')}`, lang);
}

