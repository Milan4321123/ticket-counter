/** "c12" → "Lena N." / "लेना न." — a first name and an initial, nothing more. */
export function customerName(cust: string, lang: Lang, you: string, typed?: string): string {
  if (cust === 'you') return typed ? `${typed} (${you})` : you;
  const i = Number(cust.slice(1)) || 0;
  const f = FIRST[i % FIRST.length];
  const ini = INITIAL[(i * 7 + Math.floor(i / FIRST.length)) % INITIAL.length];
  return lang === 'ne' ? `${f[1]} ${ini[1]}.` : `${f[0]} ${ini[0]}.`;
}

